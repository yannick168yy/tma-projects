const STOP_WORDS = new Set(['of', 'the', 'from', 'to', 'and'])

function splitSlug(slug: string): string[] {
  return slug.toLowerCase().split(/[-_\s]+/).filter(Boolean)
}

function titleCaseToken(token: string): string {
  if (/^\d+$/.test(token)) return token
  return token.charAt(0).toUpperCase() + token.slice(1)
}

function composeThemeLabel(
  slug: string,
  tokens: Record<string, string>,
  phrases: Record<string, string>,
  joiner: string,
): string {
  const key = slug.toLowerCase().trim()
  const phrase = phrases[key]
  if (phrase && phrase !== themeSlugFallbackLabel(slug)) return phrase
  const parts = splitSlug(slug)
  const translated = parts
    .filter((p) => !STOP_WORDS.has(p) || joiner !== '')
    .map((p) => tokens[p] ?? titleCaseToken(p))
    .filter(Boolean)
  return joiner === '' ? translated.join('') : translated.join(joiner)
}

