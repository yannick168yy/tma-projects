export function translateThemeSlug(slug: string, locale: ThemeLocale): string {
  if (!slug) return ''
  switch (locale) {
    case 'zh-CN':
      return composeThemeLabel(slug, TOKEN_ZH, MERGED_PHRASE_ZH, '')
    case 'id':
      return composeThemeLabel(slug, TOKEN_ID, MERGED_PHRASE_ID, ' ')
    case 'vi':
      return composeThemeLabel(slug, TOKEN_VI, MERGED_PHRASE_VI, ' ')
    default:
      return themeSlugFallbackLabel(slug)
  }
}

export function resolveThemeLocale(lang: string | undefined): ThemeLocale {
  if (!lang) return 'en'
  if (lang.startsWith('zh')) return 'zh-CN'
  if (lang === 'id') return 'id'
  if (lang === 'vi') return 'vi'
  return 'en'
}

