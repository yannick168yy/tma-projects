-- 024: sg_games 新增多语言游戏名称字段（印尼语/越南语/中文）
SET NAMES utf8mb4;

DROP PROCEDURE IF EXISTS `__migrate_024`;
DELIMITER $$
CREATE PROCEDURE `__migrate_024`()
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'sg_games' AND COLUMN_NAME = 'name_id'
  ) THEN
    ALTER TABLE sg_games ADD COLUMN name_id VARCHAR(255) NULL DEFAULT NULL AFTER name;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'sg_games' AND COLUMN_NAME = 'name_vi'
  ) THEN
    ALTER TABLE sg_games ADD COLUMN name_vi VARCHAR(255) NULL DEFAULT NULL AFTER name_id;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'sg_games' AND COLUMN_NAME = 'name_zh'
  ) THEN
    ALTER TABLE sg_games ADD COLUMN name_zh VARCHAR(255) NULL DEFAULT NULL AFTER name_vi;
  END IF;
END $$
DELIMITER ;
CALL `__migrate_024`();
DROP PROCEDURE IF EXISTS `__migrate_024`;
